/**
 * Безопасная сериализация данных для <script type="application/ld+json">.
 *
 * JSON.stringify не экранирует `<`, поэтому строка, содержащая `</script>`
 * (например название товара из импорта Grainger или введённое в админке),
 * закрывает тег и позволяет вставить на страницу произвольный скрипт — это XSS.
 *
 * Заменяем `<`, `>` и `&` на юникод-последовательности. Для JSON-парсера они
 * эквивалентны исходным символам, поэтому микроразметка для Google остаётся
 * полностью корректной, а разорвать ими тег уже нельзя.
 *
 * Также экранируем U+2028 и U+2029: в JSON они допустимы, но в JavaScript
 * считаются разрывом строки и ломают парсинг.
 */
export function safeJsonLd(data: unknown): string {
  return JSON.stringify(data)
    .replace(/</g, '\\u003c')
    .replace(/>/g, '\\u003e')
    .replace(/&/g, '\\u0026')
    .replace(/\u2028/g, '\\u2028')
    .replace(/\u2029/g, '\\u2029');
}
